// Builds supabase/seed.sql from data/courses/*.json (the club scorecards).
// Usage: node scripts/gen-course-seed.mjs
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';

const q = (v) => (v == null ? 'null' : typeof v === 'number' ? String(v) : `'${String(v).replace(/'/g, "''")}'`);
const arr = (xs) => `array[${xs.join(',')}]::int[]`;

const out = ['-- Generated by scripts/gen-course-seed.mjs from data/courses. Do not edit by hand.', ''];
for (const file of readdirSync('data/courses').filter((f) => f.endsWith('.json'))) {
  const { club, courses } = JSON.parse(readFileSync(`data/courses/${file}`, 'utf8'));
  for (const c of courses) {
    out.push(
      `insert into public.courses (slug, club_name, name, city, country, holes, par) values (${[c.id, club.name, c.name, club.city, club.country, c.holes, c.par].map(q).join(', ')})`,
      `  on conflict (slug) do update set name = excluded.name, holes = excluded.holes, par = excluded.par;`,
    );
    const pars = c.holeData ? arr(c.holeData.map((h) => h.par)) : 'null';
    const si = c.holeData ? arr(c.holeData.map((h) => h.strokeIndex)) : 'null';
    let order = 0;
    for (const t of c.tees) {
      for (const [who, r] of Object.entries(t.ratings)) {
        const name = who === 'ladies' ? `${t.name} · Ladies` : t.name;
        out.push(
          `insert into public.course_tees (course_id, name, color, course_rating, slope, hole_pars, stroke_index, sort_order)`,
          `  select id, ${q(name)}, ${q(t.color)}, ${r.courseRating}, ${r.slope}, ${pars}, ${si}, ${order++} from public.courses where slug = ${q(c.id)}`,
          `  on conflict (course_id, name) do update set color = excluded.color, course_rating = excluded.course_rating, slope = excluded.slope,`,
          `    hole_pars = excluded.hole_pars, stroke_index = excluded.stroke_index, sort_order = excluded.sort_order;`,
        );
      }
    }
    out.push('');
  }
}
writeFileSync('supabase/seed.sql', out.join('\n'));
console.log('wrote supabase/seed.sql');
